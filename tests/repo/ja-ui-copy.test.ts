describe('Japanese UI copy', () => {
  const messages = readLocaleMessages('ja');

  it.each(Object.entries(EXPECTED_MESSAGES))('words %s as reviewed', (key, expected) => {
    expect(messages[key]).toBe(expected);
  });

  it.each(COMPACT_KEYS)('keeps %s free of overlong katakana terms', (key) => {
    expect(key in messages, `missing ja message key: ${key}`).toBe(true);
    expect(OVERLONG_KATAKANA_TERMS.filter((term) => messages[key].includes(term))).toEqual([]);
  });
});
